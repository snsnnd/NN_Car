#!/usr/bin/env python3
"""Generate C weights for the experimental SmartLine R4 network."""

from __future__ import annotations

import json
import sys
from pathlib import Path

import numpy as np

INPUT_DIM = 7
HIDDEN = (16, 8)
OUTPUTS = 2
MATRICES = (
    ("w1", (INPUT_DIM, HIDDEN[0]), "w1"),
    ("w2", (HIDDEN[0], HIDDEN[1]), "w2"),
    ("wc", (HIDDEN[1], OUTPUTS), "w3"),
)
VECTORS = (("b1", HIDDEN[0]), ("b2", HIDDEN[1]), ("bc", OUTPUTS))


def cfloat(value: float) -> str:
    text = f"{float(value):.9g}"
    if "e" not in text and "E" not in text and "." not in text:
        text += ".0"
    return text + "f"


def load_weights(path: Path) -> tuple[dict, dict[str, np.ndarray]]:
    doc = json.loads(path.read_text(encoding="utf-8"))
    if doc.get("model") != "line_r4_mlp":
        raise ValueError(f"unexpected model: {doc.get('model')!r}")
    if int(doc.get("input_dim", -1)) != INPUT_DIM:
        raise ValueError("input_dim must be 7")
    if tuple(doc.get("hidden", ())) != HIDDEN:
        raise ValueError("hidden must be [16, 8]")
    if doc.get("activation") != "tanh" or doc.get("output") != "tanh_tanh":
        raise ValueError("activation/output do not match R4 deployment contract")
    if not doc.get("trained"):
        raise ValueError("network is not trained")
    if not np.isfinite(float(doc.get("alpha_ratio", 0.0))) or float(doc["alpha_ratio"]) <= 0.0:
        raise ValueError("alpha_ratio must be finite and positive")

    weights: dict[str, np.ndarray] = {}
    shape = doc["shape"]
    for name, expected, _ in MATRICES:
        if tuple(shape[name]) != expected:
            raise ValueError(f"shape[{name}] must be {list(expected)}")
        value = np.asarray(doc["weights"][name], dtype=np.float64)
        if value.size != expected[0] * expected[1] or not np.isfinite(value).all():
            raise ValueError(f"weights[{name}] has invalid length or value")
        weights[name] = value.reshape(expected)
    for name, size in VECTORS:
        if tuple(shape[name]) != (size,):
            raise ValueError(f"shape[{name}] must be [{size}]")
        value = np.asarray(doc["weights"][name], dtype=np.float64)
        if value.size != size or not np.isfinite(value).all():
            raise ValueError(f"weights[{name}] has invalid length or value")
        weights[name] = value
    return doc, weights


def render(doc: dict, weights: dict[str, np.ndarray], source: str) -> str:
    lines = [
        "/* Auto-generated by tools/python/gen_line_r4_nn.py.",
        f" * Source: {source}",
        f" * metrics: {json.dumps(doc.get('metrics', {}), sort_keys=True)}",
        " * Do not edit by hand. */",
        '#include "nncar/line.h"',
        "",
        "static const nncar_line_r4_nn_t g_line_r4_nn = {",
    ]
    for key, _, c_key in MATRICES:
        matrix = weights[key].T
        lines.append(f"    .{c_key} = {{")
        for row in matrix:
            lines.append("        { " + ", ".join(cfloat(v) for v in row) + " },")
        lines.append("    },")
    for key, _ in VECTORS:
        c_key = "b3" if key == "bc" else key
        lines.append(f"    .{c_key} = {{ " + ", ".join(cfloat(v) for v in weights[key]) + " },")
    lines.append(f"    .alpha_ratio = {cfloat(doc['alpha_ratio'])},")
    lines.extend((
        "};",
        "",
        "const nncar_line_r4_nn_t *nncar_line_r4_nn_trained(void)",
        "{",
        "    return &g_line_r4_nn;",
        "}",
        "",
    ))
    return "\n".join(lines)


def main(argv: list[str]) -> int:
    if len(argv) != 2:
        print(f"usage: {Path(sys.argv[0]).name} <weights.json> <out.c>", file=sys.stderr)
        return 2
    source, target = map(Path, argv)
    try:
        doc, weights = load_weights(source)
        text = render(doc, weights, str(source))
    except (OSError, KeyError, TypeError, ValueError, json.JSONDecodeError) as exc:
        print(f"gen_line_r4_nn: {exc}", file=sys.stderr)
        return 1
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
