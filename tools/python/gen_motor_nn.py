#!/usr/bin/env python3
"""Generate the C source for the trained residual motor MLP.

Usage:
    python3 tools/python/gen_motor_nn.py <weights.json> <out.c>
    python3 tools/python/gen_motor_nn.py <weights.json> <out.c> --profile <profile.json>

The JSON is written by tools/python/train_motor_nn.py. Its matrices are stored
row-major as [fan_in, fan_out] (numpy order), while nncar_motor_nn_t stores
[fan_out][fan_in], so every matrix is transposed here.

Every shape and activation is checked against the frozen constants in
motor.h; a mismatch is a hard error so the build fails instead of silently
shipping a network that does not fit the firmware.

Exit code 0 = ok, 1 = invalid weights, 2 = usage error.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import numpy as np

INPUT_DIM = 7
HIDDEN = (32, 16, 8)

# (json key, numpy shape, C rows, C cols)
MATRICES = (
    ("w1", (INPUT_DIM, HIDDEN[0]), HIDDEN[0], INPUT_DIM),
    ("w2", (HIDDEN[0], HIDDEN[1]), HIDDEN[1], HIDDEN[0]),
    ("w3", (HIDDEN[1], HIDDEN[2]), HIDDEN[2], HIDDEN[1]),
    ("w4", (HIDDEN[2], 1), 1, HIDDEN[2]),
)
VECTORS = (
    ("b1", HIDDEN[0]),
    ("b2", HIDDEN[1]),
    ("b3", HIDDEN[2]),
    ("b4", 1),
)


def _cfloat(value) -> str:
    # 9 significant digits round-trip float32 exactly.
    text = f"{float(value):.9g}"
    if "e" not in text and "E" not in text and "." not in text:
        text += ".0"
    return text + "f"


def load_weights(path: Path) -> tuple[dict, dict]:
    with path.open("r", encoding="utf-8") as fh:
        doc = json.load(fh)

    if doc.get("model") not in ("residual_mlp", "direct_mlp"):
        raise ValueError(f"unexpected model: {doc.get('model')!r}")
    if int(doc["input_dim"]) != INPUT_DIM:
        raise ValueError(f"input_dim {doc['input_dim']} != {INPUT_DIM}")
    if tuple(int(h) for h in doc["hidden"]) != HIDDEN:
        raise ValueError(f"hidden {doc['hidden']} != {list(HIDDEN)}")
    if doc.get("activation") != "relu" or doc.get("output") != "tanh":
        raise ValueError("activation/output do not match motor.h")
    if not doc.get("trained"):
        raise ValueError("network is not trained")

    shape = doc["shape"]
    weights: dict[str, np.ndarray] = {}
    for key, want, _, _ in MATRICES:
        if tuple(int(s) for s in shape[key]) != want:
            raise ValueError(f"shape[{key}] {shape[key]} != {list(want)}")
        flat = np.asarray(doc["weights"][key], dtype=np.float64)
        if flat.size != want[0] * want[1]:
            raise ValueError(f"weights[{key}] has {flat.size} values, "
                             f"expected {want[0] * want[1]}")
        weights[key] = flat.reshape(want)
    for key, size in VECTORS:
        if tuple(int(s) for s in shape[key]) != (size,):
            raise ValueError(f"shape[{key}] {shape[key]} != [{size}]")
        flat = np.asarray(doc["weights"][key], dtype=np.float64)
        if flat.size != size:
            raise ValueError(f"weights[{key}] has {flat.size} values, expected {size}")
        weights[key] = flat

    return doc, weights


def check_alpha(doc: dict, profile_path: Path) -> None:
    if doc.get("model") == "direct_mlp":
        return  # a standalone policy has no residual scale
    with profile_path.open("r", encoding="utf-8") as fh:
        profile = json.load(fh)
    trained = float(doc["alpha"])
    deployed = float(profile["motor"]["alpha"])
    if abs(trained - deployed) > 1.0e-6:
        raise ValueError(f"alpha {trained} in weights != {deployed} in "
                         f"{profile_path}; the residual would be mis-scaled")


def render(doc: dict, weights: dict, source: str) -> str:
    direct = doc.get("model") == "direct_mlp"
    symbol = ("nncar_motor_nn_direct_trained" if direct
              else "nncar_motor_nn_trained")
    static_name = "g_motor_nn_direct" if direct else "g_motor_nn"
    metrics = doc["metrics"]
    summary = (f"held-out {metrics['heldout_improvement'] * 100.0:+.1f}%"
               f", nominal {metrics['nominal_improvement'] * 100.0:+.1f}%")

    lines = [
        "/* Auto-generated by tools/python/gen_motor_nn.py.",
        f" * Source: {source}",
        f" * metrics: {summary}",
        " * Do not edit by hand. */",
        '#include "nncar/motor.h"',
        "",
        f"static const nncar_motor_nn_t {static_name} = {{",
    ]

    for key, _, rows, cols in MATRICES:
        matrix = weights[key].T  # C stores [fan_out][fan_in]
        if matrix.shape != (rows, cols):
            raise ValueError(f"{key} transposed to {matrix.shape}")
        lines.append(f"    .{key} = {{")
        for r in range(rows):
            values = ", ".join(_cfloat(v) for v in matrix[r])
            lines.append(f"        {{ {values} }},")
        lines.append("    },")

    for key, size in VECTORS:
        values = ", ".join(_cfloat(v) for v in weights[key])
        lines.append(f"    .{key} = {{ {values} }},")

    lines += [
        "};",
        "",
        f"const nncar_motor_nn_t *{symbol}(void)",
        "{",
        f"    return &{static_name};",
        "}",
        "",
    ]
    return "\n".join(lines)


def main(argv: list[str]) -> int:
    paths: list[str] = []
    profile: Path | None = None

    i = 0
    while i < len(argv):
        if argv[i] == "--profile":
            if i + 1 >= len(argv):
                print(__doc__.strip(), file=sys.stderr)
                return 2
            profile = Path(argv[i + 1])
            i += 2
        elif argv[i].startswith("--"):
            print(__doc__.strip(), file=sys.stderr)
            return 2
        else:
            paths.append(argv[i])
            i += 1

    if len(paths) != 2:
        print(__doc__.strip(), file=sys.stderr)
        return 2

    source = Path(paths[0])
    target = Path(paths[1])

    try:
        doc, weights = load_weights(source)
        if profile is not None:
            check_alpha(doc, profile)
        text = render(doc, weights, str(source))
    except (OSError, KeyError, TypeError, ValueError) as exc:
        print(f"gen_motor_nn: {exc}", file=sys.stderr)
        return 1

    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
